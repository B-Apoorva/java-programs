package javaq;

public class NewEmployee {

	private String empName;
	private String city;
	private String empId;
	
	public NewEmployee() {
		//Default constructor
	}
	
	public NewEmployee(String city, String empName, String empId) {
		this.city=city;
		this.empName=empName;
		this.empId=empId;
		
	}
	
}
